-- Защита строителя от выдуманных дверей/окон: добавляем правило в активный builder-промт.
UPDATE architect_prompts
SET system = system || E'\n- Дверь/окно указывай только если они явно видны как дверь/окно: полотно, наличник, ручка, створка, рама, подоконник, направление открывания. Цветная полоса, край стены, проём без полотна, тень или кусок отделки — не дверь и не окно. Если не видно — null.\n- Не добавляй дверь/окно, которых нет на фото.'
WHERE kind = 'builder'
  AND active = true
  AND system NOT LIKE '%Не добавляй дверь/окно%';
