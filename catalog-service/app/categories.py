def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", str(text or "").lower().replace("ё", "е")).strip()


def map_category(category_raw: str, name: str = "") -> str | None:
    """Возвращает внутреннюю категорию по категории источника и названию."""
    for source in (category_raw, name):
        text = _norm(source)
        if not text:
            continue
        best: str | None = None
        best_score = 0
        for category, words in CATEGORY_WORDS:
            score = sum(len(w) for w in words if w in text)
            if score > best_score:
                best_score = score
                best = category
        if best is not None:
            return best
    return None
