def _norm(text: str) -> str:
    value = str(text or "").lower().replace("ё", "е")
    value = re.sub(r"[^0-9a-zа-я]+", " ", value)
    return re.sub(r"\s+", " ", value).strip()


def _match_rule(rule: str, text: str) -> bool:
    words = rule.split()
    return bool(words) and all(word in text for word in words)


def map_category_path(path: str, name: str = "") -> str | None:
    """Определяет внутреннюю категорию по полному пути поставщика.

    Сначала матчим по пути (все слова правила должны встречаться), затем по
    названию товара, затем — фолбэк по корневому разделу.
    """
    path_text = _norm(path)
    for key, words in PATH_RULES:
        if any(_match_rule(word, path_text) for word in words):
            return key
    name_text = _norm(name)
    if name_text:
        for key, words in PATH_RULES:
            if any(_match_rule(word, name_text) for word in words):
                return key
    root = path_text.split(" ")[0] if path_text else ""
    return ROOT_FALLBACK.get(root, "other")


def map_category(category_raw: str, name: str = "") -> str | None:
    """Совместимость: маппинг по названию категории и названию товара."""
    return map_category_path(category_raw or "", name)
