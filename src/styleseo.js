const byKey = new Map(STYLE_SEO.map(s => [s.key, s]));
const byName = new Map(STYLE_SEO.map(s => [s.name.toLowerCase(), s]));

export function styleSeoByKey(key) {
  return byKey.get(String(key || "")) || null;
}

// Имя стиля (display_name из статей/БД) -> key; точное совпадение без учёта регистра.
export function styleKeyByName(name) {
  const s = String(name || "").trim();
  if (byKey.has(s)) return s;
  return byName.get(s.toLowerCase())?.key || null;
}

